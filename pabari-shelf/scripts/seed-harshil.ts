import { Pool } from 'pg'

const pool = new Pool({ connectionString: process.env.DATABASE_URL })

async function getOrCreate(name: string, parentId: string | null, color: string): Promise<string> {
  const existing = await pool.query(
    `SELECT id FROM shelf_folders WHERE name = $1 AND ${parentId ? 'parent_id = $2' : 'parent_id IS NULL'}`,
    parentId ? [name, parentId] : [name]
  )
  if (existing.rows.length) return existing.rows[0].id
  const res = await pool.query(
    `INSERT INTO shelf_folders (name, color, parent_id, created_by) VALUES ($1, $2, $3, 'system') RETURNING id`,
    [name, color, parentId]
  )
  return res.rows[0].id
}

